async (page) => {
  const base = new URL(page.url()).origin;
  const results = [], errors = [];
  const onError = error => errors.push(error.message);
  const onResponse = response => { if (response.url().startsWith(base + '/') && response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); };
  page.on('pageerror', onError);
  page.on('response', onResponse);
  const check = (condition, label) => { if (!condition) throw new Error(label); results.push(label); };
  const settle = async () => { await page.evaluate(() => document.fonts.ready); await page.waitForTimeout(750); };
  await page.setViewportSize({ width: 1440, height: 960 });
  let releaseMedia;
  const mediaHeld = new Promise(resolve => { releaseMedia = resolve; });
  await page.route('**/media/digital-market/*', async route => {
    await mediaHeld;
    await route.continue();
  });
  await page.goto(base + '/', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(3900);
  check(await page.locator('[data-home-media-status]').getAttribute('data-home-media-status') === 'loading', 'Opening waits for homepage media');
  check(await page.locator('[data-home-media-progress]').getAttribute('data-home-media-progress') === '0%', 'Homepage byte progress starts at zero percent');
  check(await page.locator('.opening-index').textContent() === 'LOADING / 0%', 'Loading label uses percentage');
  check(await page.locator('.opening-sequence').evaluate(e => getComputedStyle(e).visibility) === 'visible', 'Opening remains visible while media is delayed');
  releaseMedia();
  await page.waitForFunction(() => document.querySelector('main')?.dataset.homeMediaStatus === 'ready');
  await page.waitForFunction(() => !document.documentElement.classList.contains('motion-opening'));
  await page.unroute('**/media/digital-market/*');
  check(await page.locator('[data-home-media-status]').getAttribute('data-home-media-status') !== 'loading', 'Opening releases after delayed media settles');
  await page.goto(base + '/');
  await page.waitForTimeout(3900);
  await page.route('**/media/digital-market/employee-41-workflow-screen-v1.webp', route => route.abort());
  await page.goto(base + '/');
  await page.waitForTimeout(3900);
  check(await page.locator('[data-home-media-status]').getAttribute('data-home-media-status') === 'ready-with-errors', 'Failed homepage media still settles');
  check(await page.locator('.opening-sequence').evaluate(e => getComputedStyle(e).visibility) === 'hidden', 'Failed media does not block opening');
  await page.unroute('**/media/digital-market/employee-41-workflow-screen-v1.webp');
  await page.goto(base + '/');
  await page.waitForTimeout(3900);
  check(await page.getByRole('heading', { level: 1 }).getAttribute('aria-label') === '数字超市 DIGITAL MARKET', 'Accessible homepage heading');
  check(await page.locator('.hero-release-card').count() === 5, 'Five covers in the reference arc');
  check(await page.locator('#works .purpose-card').count() === 4, 'Four project purpose cards in the staggered grid');
  check(await page.locator('#works h2').getAttribute('aria-label') === 'WHY WE BUILD', 'Project purpose section heading');
  check(await page.locator('#works a[href^="/employee/"]').count() === 0, 'Purpose section does not repeat employee profiles');
  check(await page.locator('.hero-works-cta').getAttribute('href') === '/employees', 'Explore employees CTA opens employee directory');
  const featuredLinks = await page.locator('.hero-release-card').evaluateAll(cards => cards.map(card => card.getAttribute('href')));
  const lowerLinks = await page.locator('.editorial-section a[href^="/employee/"]').evaluateAll(links => links.map(link => link.getAttribute('href')));
  check(lowerLinks.every(link => !featuredLinks.includes(link)), 'Featured employees do not repeat below the hero');
  const galleryTitles = await page.locator('.portrait-panel').evaluateAll(panels => panels.map(panel => panel.getAttribute('aria-label').replace(/^展开/, '')));
  const heroTitles = await page.locator('.hero-release-card b').allTextContents();
  const projectTitles = await page.locator('.project-caption h3').allTextContents();
  check(galleryTitles.every(title => !heroTitles.includes(title) && !projectTitles.includes(title)), 'The three homepage galleries use separate employee groups');
  check(await page.locator('.portrait-panel').count() === 5, 'About retains its five-panel accordion');
  check(await page.locator('.strength-card').count() === 4, 'Four capability columns');
  check(await page.locator('[data-home-media-total]').getAttribute('data-home-media-total') === '15', 'Homepage preloads all configured images');
  check(await page.locator('.opening-sequence').evaluate(e => getComputedStyle(e).visibility) === 'hidden', 'Opening panels finish and release page');
  check(await page.evaluate(() => !document.documentElement.classList.contains('motion-opening')), 'Opening scroll lock is released');
  const before = await page.locator('.hero-release-glow').first().evaluate(e => getComputedStyle(e).transform);
  await page.locator('.hero-release-card').first().hover();
  await page.waitForTimeout(600);
  const after = await page.locator('.hero-release-glow').first().evaluate(e => getComputedStyle(e).transform);
  check(before !== after, 'Cover hover lifts and straightens the cover');
  await page.getByRole('link', { name: '关于', exact: true }).first().click();
  await page.waitForTimeout(2400);
  check(await page.evaluate(() => Math.abs(document.querySelector('#about').getBoundingClientRect().top - 82) < 3), 'Header anchor lands below fixed header');
  await page.locator('.portrait-panel').first().click();
  check(await page.locator('.portrait-panel').first().getAttribute('aria-pressed') === 'true', 'Accordion click selects panel');
  await page.keyboard.press('ArrowRight');
  check(await page.locator('.portrait-panel').nth(1).getAttribute('aria-pressed') === 'true', 'Accordion supports arrow keys');
  await page.keyboard.press('End');
  check(await page.locator('.portrait-panel').nth(4).getAttribute('aria-pressed') === 'true', 'Accordion supports End key');
  await page.locator('.portrait-detail').click();
  check(page.url().endsWith('/employee/employee-08'), 'Accordion link opens its newly assigned employee');
  await page.getByRole('link', { name: '全部员工', exact: true }).first().click();
  await settle();
  const source = await page.evaluate(async () => (await import('/src/data/catalog.js')).employees);
  check(await page.locator('#catalog .employee-card').count() === 9, 'Initial directory shows nine employees');
  for (const [category, label] of [['office', '办公协作'], ['creative', '内容创作'], ['research', '数据研究'], ['service', '客户服务'], ['finance', '财务法务'], ['specialist', '专业助手']]) {
    await page.getByRole('button', { name: new RegExp('^' + label) }).click();
    check(await page.locator('#catalog .employee-card').count() === source.filter(e => e.category === category).length, `${label} filter count`);
  }
  await page.getByRole('button', { name: /^全部员工/ }).click();
  await page.getByRole('textbox', { name: '搜索数字员工' }).fill('documind');
  check(await page.locator('#catalog .employee-card').count() === 1, 'Case-insensitive project search');
  check(await page.locator('#catalog .employee-card h3').innerText() === '财务票据处理员', 'Correct search result');
  await page.getByRole('textbox', { name: '搜索数字员工' }).fill('nothing-matches-82373');
  check(await page.getByText('还没有找到匹配的数字员工').isVisible(), 'Empty search state');
  await page.getByRole('button', { name: '查看全部员工', exact: true }).click();
  check(await page.getByRole('textbox', { name: '搜索数字员工' }).inputValue() === '', 'Search reset');
  await page.getByRole('button', { name: '列表视图', exact: true }).click();
  check(await page.locator('#catalog .is-list').count() === 1, 'List view');
  await page.getByRole('combobox', { name: '员工排序' }).selectOption('name');
  const first = [...source].sort((a, b) => a.title.localeCompare(b.title, 'zh-CN'))[0].title;
  check(await page.locator('#catalog .employee-card h3').first().innerText() === first, 'Name ordering');
  await page.getByRole('combobox', { name: '员工排序' }).selectOption('featured');
  check(await page.locator('#catalog .employee-card').first().locator('.employee-copy').getAttribute('href') === '/employee/employee-07', 'Featured ordering');
  await page.getByRole('combobox', { name: '员工排序' }).selectOption('source');
  await page.getByRole('button', { name: '网格视图', exact: true }).click();
  while (await page.getByRole('button', { name: /^发现更多员工/ }).count()) await page.getByRole('button', { name: /^发现更多员工/ }).click();
  check(await page.locator('#catalog .employee-card').count() === source.length, 'All source employees are reachable');
  await page.getByRole('button', { name: /^财务法务/ }).click();
  await page.getByRole('textbox', { name: '搜索数字员工' }).fill('DocuMind');
  await page.locator('#catalog .employee-card').click();
  await settle();
  check(page.url().endsWith('/employee/employee-09'), 'Directory opens correct detail');
  await page.locator('.breadcrumbs').getByRole('link', { name: '全部员工', exact: true }).click();
  check(await page.getByRole('textbox', { name: '搜索数字员工' }).inputValue() === 'DocuMind', 'Detail return preserves search');
  check(await page.getByRole('button', { name: /^财务法务/ }).getAttribute('aria-pressed') === 'true', 'Detail return preserves category');
  await page.goto(base + '/#capabilities');
  await page.locator('.strength-card').nth(1).click();
  check(await page.getByRole('button', { name: /^内容创作/ }).getAttribute('aria-pressed') === 'true', 'Capability links apply category');
  await page.getByRole('textbox', { name: '搜索数字员工' }).fill('Presenton');
  await page.locator('#catalog .employee-card').click();
  await page.goBack();
  check(await page.getByRole('textbox', { name: '搜索数字员工' }).inputValue() === 'Presenton', 'Browser Back preserves category-entry search');
  for (const employee of source) {
    await page.goto(`${base}/employee/${employee.id}`);
    check(await page.getByRole('heading', { level: 1 }).innerText() === employee.title, `${employee.id} direct detail route`);
    check(await page.locator('.original-description').innerText() === employee.description, `${employee.id} complete source description`);
  }
  await page.goto(base + '/employee/unknown');
  check(await page.getByRole('heading', { name: /这位数字同事/ }).isVisible(), 'Unknown employee recovery page');
  await page.getByRole('link', { name: '返回全部员工', exact: true }).click();
  check(page.url().endsWith('/employees'), 'Recovery link works');
  check(errors.length === 0, `No runtime or HTTP errors (${errors.length})`);
  page.off('pageerror', onError);
  page.off('response', onResponse);
  return { passed: results.length, results, errors };
}
