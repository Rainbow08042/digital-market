async (page) => {
  const base = new URL(page.url()).origin;
  const checks = [], errors = [];
  const check = (ok, label) => { if (!ok) throw new Error(label); checks.push(label); };
  page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(base + '/?hero-video=review');
  check(await page.locator('.hero-scene video').count() === 1, 'Hero uses the supplied video');
  const video = page.locator('.hero-scene video');
  await page.waitForFunction(() => document.querySelector('main').dataset.homeMediaStatus === 'ready');
  check(await video.evaluate(v => v.paused && v.currentTime === 0), 'Reduced motion keeps the video paused on its poster');
  check(await video.evaluate(v => v.muted && v.loop && v.playsInline && v.poster.endsWith('/storefront.webp')), 'Muted inline loop retains the original image as poster');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.waitForFunction(() => { const v = document.querySelector('.hero-scene video'); return !v.paused && v.currentTime > .3; });
  await page.waitForFunction(() => !document.documentElement.classList.contains('motion-opening') && getComputedStyle(document.querySelector('.opening-sequence')).visibility === 'hidden');
  const fixedFrame = await video.evaluate(async v => {
    v.pause();
    const first = v.getBoundingClientRect(), time = v.currentTime;
    await new Promise(resolve => setTimeout(resolve, 600));
    const last = v.getBoundingClientRect();
    return { timeUnchanged: v.currentTime === time, animation: getComputedStyle(v).animationName, shift: Math.max(...['left', 'top', 'width', 'height'].map(key => Math.abs(last[key] - first[key]))) };
  });
  check(fixedFrame.timeUnchanged && fixedFrame.animation === 'none' && fixedFrame.shift < .05, 'Paused video frame has no page-induced camera movement');
  await video.evaluate(v => v.play());
  const sceneTop = await page.locator('.hero-scene').evaluate(e => e.getBoundingClientRect().top + scrollY);
  await page.evaluate(() => window.scrollTo({ top: 200, behavior: 'instant' }));
  await page.waitForTimeout(1400);
  const scrolledSceneTop = await page.locator('.hero-scene').evaluate(e => e.getBoundingClientRect().top + scrollY);
  check(Math.abs(scrolledSceneTop - sceneTop) < .1, 'Video scene does not acquire a second camera from scroll parallax');
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  check(await video.evaluate(v => v.videoWidth === 1918 && v.videoHeight === 1080 && Math.abs(v.duration - 6) < .1), 'Web video decodes at full resolution and six-second duration');
  await video.evaluate(v => { v.currentTime = v.duration - .25; });
  await page.waitForFunction(() => document.querySelector('.hero-scene video').currentTime < .5);
  check(await video.evaluate(v => !v.paused && !v.ended), 'Video loops back to the beginning');
  await page.locator('#about').scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('.hero-scene video').paused);
  check(await video.evaluate(v => v.paused), 'Video pauses when the hero leaves the viewport');
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await page.waitForFunction(() => !document.querySelector('.hero-scene video').paused);
  check(await video.evaluate(v => !v.paused), 'Video resumes on return to the hero');
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: width > 700 ? 1000 : 844 });
    await page.waitForTimeout(300);
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Video homepage fits ${width}px`);
    check(await video.evaluate(v => getComputedStyle(v).objectFit === 'cover' && v.clientWidth > 0 && v.clientHeight > 0), `Video preserves cover layout at ${width}px`);
    check(await video.evaluate(v => getComputedStyle(v).animationName === 'none' && getComputedStyle(v).transform === 'none'), `Video has no extra scale or translation animation at ${width}px`);
    if (width !== 320) await page.screenshot({ path: `output/playwright/hero-video-${width}.png` });
  }
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.waitForFunction(() => document.querySelector('.hero-scene video').paused);
  check(await video.evaluate(v => v.paused), 'Enabling reduced motion stops playback');
  let release;
  const hold = new Promise(resolve => { release = resolve; });
  await page.route('**/storefront-loop-v1.mp4', async route => { await hold; await route.continue(); });
  await page.goto(base + '/?hero-video=stalled');
  await page.waitForFunction(() => document.querySelector('main').dataset.homeMediaStatus === 'ready');
  check(await page.locator('.opening-sequence').evaluate(e => getComputedStyle(e).visibility === 'hidden'), 'Stalled video does not block the image loading gate or page reveal');
  check(await page.locator('.hero-scene video').getAttribute('poster') === '/media/digital-market/storefront.webp', 'Stalled video retains the original poster');
  release();
  await page.waitForFunction(() => document.querySelector('.hero-scene video').readyState >= 2);
  await page.unroute('**/storefront-loop-v1.mp4');
  await page.route('**/storefront-loop-v1.mp4', route => route.abort());
  await page.goto(base + '/?hero-video=failed');
  await page.waitForFunction(() => document.querySelector('main').dataset.homeMediaStatus === 'ready');
  check(await page.locator('h1').getAttribute('aria-label') === '数字超市 DIGITAL MARKET', 'Video failure leaves homepage content available');
  check(await page.locator('.hero-scene video').getAttribute('poster') === '/media/digital-market/storefront.webp', 'Failed video retains its poster fallback');
  await page.unroute('**/storefront-loop-v1.mp4');
  check(errors.length === 0, 'No browser runtime errors');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(base + '/');
  await page.waitForFunction(() => !document.documentElement.classList.contains('motion-opening') && document.querySelector('main').dataset.homeMediaStatus === 'ready');
  check(await page.locator('.opening-sequence').evaluate(e => getComputedStyle(e).visibility === 'hidden'), 'Normal homepage opening completes with video');
  return { total: checks.length, checks, errors };
}
